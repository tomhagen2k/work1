import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import process from 'node:process';
import console from 'node:console';
import path from 'node:path';
import { fileURLToPath, URL } from 'node:url';

const appRoot = fileURLToPath(new URL('../', import.meta.url));
const workspace = path.resolve(appRoot, '..');
const directory = path.join(appRoot, 'tests/reference/demo-v1.5');
const manifestPath = path.join(directory, 'manifest.json');
const raw = await readFile(manifestPath);
const manifest = JSON.parse(raw);
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex');

assert.equal(manifest.inventory.version, '1.5');
assert.equal(manifest.records.length, 108);
assert.equal(manifest.inventory.levels.length, 44);
assert.equal(
  manifest.inventory.levels.filter((level) => level.bonus).length,
  4,
);
assert.equal(
  new Set(manifest.inventory.levels.map((level) => level.index)).size,
  44,
);
assert(
  manifest.inventory.levels.every(
    (level) => level.chapter >= 1 && level.chapter <= 4,
  ),
);
assert.equal(manifest.inventory.skins.length, 31);
assert.equal(
  manifest.assets.filter((asset) => asset.path.endsWith('.webp')).length,
  22,
);
assert.deepEqual(manifest.errors, []);
assert.deepEqual(manifest.network, []);
assert(manifest.protectedSourcesUnchanged);

let bytes = 0;
for (const record of manifest.records) {
  const png = await readFile(path.join(directory, record.file));
  bytes += png.length;
  assert.equal(png.subarray(1, 4).toString(), 'PNG');
  assert.equal(png.readUInt32BE(16), record.viewport.width);
  assert.equal(png.readUInt32BE(20), record.viewport.height);
  assert.equal(sha(png), record.sha256, `Screenshot modified: ${record.file}`);
  assert(record.sameFrozenFrameStable, `Unstable frozen frame: ${record.file}`);
  assert(record.fontLoaded, `Font missing: ${record.file}`);
}
for (const tag of ['844x390', '667x375']) {
  const pngs = (await readdir(path.join(directory, tag))).filter((name) =>
    name.endsWith('.png'),
  );
  assert.equal(pngs.length, 54);
  assert.equal(
    new Set(
      manifest.records
        .filter((record) => record.file.startsWith(tag))
        .map((record) => record.id),
    ).size,
    54,
  );
}
const capturedOverlays = new Set(
  manifest.records.flatMap((record) => record.overlays),
);
for (const overlay of manifest.inventory.overlays)
  assert(
    capturedOverlays.has(overlay.id),
    `Overlay not captured: ${overlay.id}`,
  );
for (const [name, expected] of Object.entries(manifest.sourceHashes))
  assert.equal(
    sha(await readFile(path.join(workspace, name))),
    expected,
    `Source modified: ${name}`,
  );
for (const asset of manifest.assets)
  assert.equal(
    sha(await readFile(path.join(workspace, asset.path))),
    asset.sha256,
    `Asset modified: ${asset.path}`,
  );

// Existing references must never be silently regenerated by a routine test run.
const guard = spawnSync(
  process.execPath,
  [path.join(appRoot, 'scripts/capture-demo-reference.mjs')],
  { encoding: 'utf8' },
);
assert.equal(guard.status, 1);
assert(guard.stderr.includes('Reference already exists'));
assert.equal(sha(await readFile(manifestPath)), sha(raw));

const report = {
  verifiedAt: new Date().toISOString(),
  result: 'pass',
  screenshots: 108,
  statesPerViewport: 54,
  overlayContainersCovered: capturedOverlays.size,
  levels: 44,
  skins: 31,
  webpAssets: 22,
  screenshotBytes: bytes,
  checks: [
    'PNG dimensions and SHA-256',
    'unique IDs and chapter mapping',
    'Nunito loaded',
    'same frozen-frame stability',
    'all 21 overlay containers captured',
    'source and art fingerprints unchanged',
    'no recorded page/network errors',
    'explicit refresh guard',
  ],
  limitations:
    'Reference integrity only; not visual parity of the mobile app, gameplay acceptance, cross-run pixel determinism, native or physical-device testing.',
};
await writeFile(
  path.join(directory, 'verification.json'),
  `${JSON.stringify(report, null, 2)}\n`,
);
console.log(JSON.stringify(report, null, 2));
